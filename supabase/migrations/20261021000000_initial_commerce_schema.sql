create extension if not exists pgcrypto;

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now()
);

create or replace function public.create_profile_for_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, role)
  values (new.id, 'customer')
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created_profile
  after insert on auth.users
  for each row execute procedure public.create_profile_for_auth_user();

insert into public.profiles (id, role)
select id, 'customer'
from auth.users
on conflict (id) do nothing;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and role = 'admin'
  );
$$;

grant execute on function public.is_admin() to anon, authenticated;

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  full_name text not null,
  phone text not null,
  address text not null,
  city text not null,
  postcode text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint customers_email_lowercase check (email = lower(email))
);

create table public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  sku text not null unique,
  brand text not null,
  product_type text not null check (product_type in ('Clothing', 'Shoes', 'Bags', 'Accessories')),
  gender text not null check (gender in ('Men', 'Women', 'Kids', 'Unisex')),
  price numeric(12, 2) not null check (price >= 0),
  original_price numeric(12, 2) check (original_price is null or original_price >= price),
  stock integer not null default 0 check (stock >= 0),
  image_url text not null default '',
  colors text[] not null default '{}',
  sizes text[] not null default '{}',
  rating numeric(3, 2) not null default 0 check (rating between 0 and 5),
  reviews integer not null default 0 check (reviews >= 0),
  badge text,
  badge_color text,
  is_new boolean not null default false,
  is_sale boolean not null default false,
  is_active boolean not null default true,
  units_sold integer not null default 0 check (units_sold >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.promotions (
  id bigint generated by default as identity primary key,
  code text not null unique,
  discount_type text not null check (discount_type in ('percentage', 'fixed_amount', 'free_shipping')),
  discount_value numeric(12, 2) not null default 0 check (discount_value >= 0),
  minimum_subtotal numeric(12, 2) not null default 0 check (minimum_subtotal >= 0),
  usage_limit integer check (usage_limit is null or usage_limit > 0),
  usage_count integer not null default 0 check (usage_count >= 0),
  starts_at timestamptz,
  expires_at timestamptz,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint promotions_code_uppercase check (code = upper(code)),
  constraint promotions_expiry_after_start check (expires_at is null or starts_at is null or expires_at > starts_at),
  constraint promotions_percentage_range check (discount_type <> 'percentage' or discount_value <= 100)
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  customer_id uuid not null references public.customers (id),
  subtotal numeric(12, 2) not null check (subtotal >= 0),
  discount_amount numeric(12, 2) not null default 0 check (discount_amount >= 0),
  total numeric(12, 2) not null check (total >= 0),
  promotion_id bigint references public.promotions (id) on delete set null,
  promotion_code text,
  status text not null default 'Pending' check (status in ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled')),
  payment_status text not null default 'Not Paid' check (payment_status in ('Not Paid', 'Paid', 'Refunded')),
  payment_method text not null default 'Manual',
  delivery_fee numeric(12, 2) not null default 0 check (delivery_fee >= 0),
  delivery_zone text not null default 'CBD',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  product_id bigint references public.products (id) on delete set null,
  product_name text not null,
  product_sku text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  line_total numeric(12, 2) generated always as (quantity * unit_price) stored
);

create table public.promotion_redemptions (
  id bigint generated by default as identity primary key,
  promotion_id bigint not null references public.promotions (id),
  order_id uuid not null unique references public.orders (id) on delete cascade,
  customer_id uuid not null references public.customers (id),
  discount_amount numeric(12, 2) not null default 0 check (discount_amount >= 0),
  redeemed_at timestamptz not null default now()
);

